-- One row per concern/source for the output of the visual AI or questionnaire
-- LLM. The same concern can therefore have two independent explanations.
CREATE TABLE IF NOT EXISTS session_skin_concern_detection (
    detection_id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id                 UUID NOT NULL,
    concern_id                 VARCHAR(10) NOT NULL,
    detection_source           VARCHAR(20) NOT NULL,
    image_id                   UUID,
    questionnaire_response_id  UUID,
    skin_concern_exists        BOOLEAN NOT NULL,
    if_skin_concern_true_why   TEXT NOT NULL DEFAULT '',
    raw_detection_json         JSONB,
    detected_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_detection_session
        FOREIGN KEY (session_id)
        REFERENCES customer_session(session_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_detection_concern
        FOREIGN KEY (concern_id)
        REFERENCES skin_concern(concern_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_detection_image
        FOREIGN KEY (image_id)
        REFERENCES skin_image(image_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_detection_questionnaire
        FOREIGN KEY (questionnaire_response_id)
        REFERENCES questionnaire_response(questionnaire_response_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT ck_detection_source CHECK (
        detection_source IN ('IMAGE', 'QUESTIONNAIRE')
    ),

    CONSTRAINT ck_detection_source_reference CHECK (
        (detection_source = 'IMAGE'
            AND image_id IS NOT NULL
            AND questionnaire_response_id IS NULL)
        OR
        (detection_source = 'QUESTIONNAIRE'
            AND questionnaire_response_id IS NOT NULL
            AND image_id IS NULL)
    )
);

COMMENT ON TABLE session_skin_concern_detection IS
'Stores the independent visual-AI and questionnaire-LLM detection results, including the exact explanation text supplied by each model.';

