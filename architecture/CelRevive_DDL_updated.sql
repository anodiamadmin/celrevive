-- A foreign key guarantees that a base-active compatibility row exists, while
-- this trigger guarantees that the referenced compatibility row is actually
-- marked compatible.
CREATE OR REPLACE FUNCTION validate_recommendation_active_compatibility()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM base_active_compatibility bac
        WHERE bac.base_id = NEW.base_id
          AND bac.active_id = NEW.active_id
          AND bac.is_compatible = TRUE
    ) THEN
        RAISE EXCEPTION
            'Active % is not marked compatible with base %',
            NEW.active_id, NEW.base_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_recommendation_active_compatibility
    ON recommendation_active;

CREATE TRIGGER trg_validate_recommendation_active_compatibility
BEFORE INSERT OR UPDATE OF base_id, active_id
ON recommendation_active
FOR EACH ROW
EXECUTE FUNCTION validate_recommendation_active_compatibility();

