        PRIMARY KEY (concern_id, benefit_id, mapping_version),

    CONSTRAINT fk_cb_concern
        FOREIGN KEY (concern_id)
        REFERENCES skin_concern(concern_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_cb_benefit
        FOREIGN KEY (benefit_id)
        REFERENCES benefit(benefit_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

