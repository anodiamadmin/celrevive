-- A customer_session represents one execution of the CelRevive recommendation
-- widget for a Shopify customer. Shopify remains the system of record for
-- authentication, cart, checkout and order state; this table stores only the
-- identifiers needed to correlate the recommendation workflow.
CREATE TABLE IF NOT EXISTS customer_session (
    session_id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    shopify_customer_id    VARCHAR(100),
    shopify_customer_email VARCHAR(320),
    shopify_cart_id        VARCHAR(255),
    shopify_checkout_id    VARCHAR(255),
    consent_given          BOOLEAN NOT NULL DEFAULT FALSE,
    session_status         VARCHAR(30) NOT NULL DEFAULT 'STARTED',
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes                  TEXT,

    CONSTRAINT ck_customer_session_status CHECK (
        session_status IN (
            'STARTED',
            'IMAGE_RECEIVED',
            'QUESTIONNAIRE_COMPLETED',
            'CONCERNS_COMBINED',
            'RECOMMENDATION_GENERATED',
            'RETURNED_TO_WIDGET',
            'ABANDONED',
            'ERROR'
        )
    )
);

COMMENT ON TABLE customer_session IS
'One CelRevive recommendation-widget execution. Shopify remains the source of truth for authentication, cart, checkout and order transactions.';

-- Structured profile/environment data used for recommendation filtering.
-- The original questionnaire JSON remains stored verbatim in
-- questionnaire_response.response_json.
CREATE TABLE IF NOT EXISTS session_profile (
    session_id             UUID PRIMARY KEY,
    age                    SMALLINT,
    skin_type              VARCHAR(50),
    location_country       VARCHAR(100),
    location_region        VARCHAR(100),
    location_city          VARCHAR(150),
    climate                VARCHAR(100),
    environment            VARCHAR(100),
    weather_snapshot       JSONB,
    acne_suitable_required BOOLEAN,
    texture_preference     VARCHAR(100),
    primary_goal           VARCHAR(255),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_session_profile_session
        FOREIGN KEY (session_id)
        REFERENCES customer_session(session_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT ck_session_profile_age CHECK (
        age IS NULL OR (age >= 0 AND age <= 150)
    )
);

COMMENT ON TABLE session_profile IS
'Structured recommendation inputs extracted from questionnaire/context, including age, skin type and location/weather context. Raw questionnaire answers are preserved separately.';

