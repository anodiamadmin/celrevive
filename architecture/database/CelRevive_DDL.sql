-- 8. DERIVED RECOMMENDATION VIEWS
-- ============================================================================

-- Latest version of each concern->benefit mapping, independently per concern.
CREATE OR REPLACE VIEW vw_current_concern_benefit AS
SELECT cb.*
FROM concern_benefit cb
JOIN (
    SELECT concern_id, MAX(mapping_version) AS mapping_version
    FROM concern_benefit
    GROUP BY concern_id
) latest
  ON latest.concern_id = cb.concern_id
 AND latest.mapping_version = cb.mapping_version;

-- Latest score version for each active-benefit pair.
CREATE OR REPLACE VIEW vw_current_active_benefit_score AS
SELECT abs.*
FROM active_benefit_score abs
JOIN (
    SELECT active_id, benefit_id, MAX(score_version) AS score_version
    FROM active_benefit_score
    GROUP BY active_id, benefit_id
) latest
  ON latest.active_id = abs.active_id
 AND latest.benefit_id = abs.benefit_id
 AND latest.score_version = abs.score_version;

-- Derived Active <-> Skin Concern score.
-- No physical active_concern mapping table is required.
--
-- weighted_score_0_20:
--   SUM(weight * active_benefit_score)
--
-- relevance_score_0_100:
--   weighted_score_0_20 * 5
--
-- Missing active-benefit rows are treated as score 0 and are NOT silently
-- renormalised away.
CREATE OR REPLACE VIEW vw_active_concern_score AS
SELECT
    cb.concern_id,
    sc.concern_name,
    a.active_id,
    a.active_name,
    cb.mapping_version,
    ROUND(
        SUM(cb.weight * COALESCE(abs.score, 0))
        / NULLIF(SUM(cb.weight), 0),
        4
    ) AS weighted_score_0_20,
    ROUND(
        5 * SUM(cb.weight * COALESCE(abs.score, 0))
        / NULLIF(SUM(cb.weight), 0),
        2
    ) AS relevance_score_0_100,
    CASE MIN(
        CASE cb.evidence_level
            WHEN 'HYPOTHESIS' THEN 1
            WHEN 'EXPERT'     THEN 2
            WHEN 'VALIDATED'  THEN 3
        END
    )
        WHEN 1 THEN 'HYPOTHESIS'
        WHEN 2 THEN 'EXPERT'
        WHEN 3 THEN 'VALIDATED'
    END AS mapping_evidence_floor,
    COUNT(*) AS mapped_benefit_count
FROM vw_current_concern_benefit cb
JOIN skin_concern sc
  ON sc.concern_id = cb.concern_id
CROSS JOIN active a
LEFT JOIN vw_current_active_benefit_score abs
  ON abs.active_id = a.active_id
 AND abs.benefit_id = cb.benefit_id
GROUP BY
    cb.concern_id,
    sc.concern_name,
    a.active_id,
    a.active_name,
    cb.mapping_version;

-- Ranked recommendation view for convenient API/query consumption.
CREATE OR REPLACE VIEW vw_ranked_active_concern_score AS
SELECT
    x.*,
    DENSE_RANK() OVER (
        PARTITION BY x.concern_id
        ORDER BY x.relevance_score_0_100 DESC, x.active_id
    ) AS active_rank
FROM vw_active_concern_score x;

COMMENT ON VIEW vw_active_concern_score IS
'Derived active-to-skin-concern relevance. Do not replace with a manually maintained direct mapping table.';

COMMENT ON VIEW vw_ranked_active_concern_score IS
'Ranks all actives for each skin concern using the latest concern-benefit mapping and active-benefit scores.';

-- ============================================================================
-- 9. OPTIONAL VALIDATION / QA VIEWS
-- ============================================================================

-- Should return zero rows when all concern/version weight sets are valid.
CREATE OR REPLACE VIEW vw_invalid_concern_benefit_weight_sum AS
SELECT
    concern_id,
    mapping_version,
    SUM(weight) AS weight_sum
FROM concern_benefit
GROUP BY concern_id, mapping_version
HAVING ABS(SUM(weight) - 1.00000) > 0.00001;

-- Identifies missing active-benefit score cells for the current benefit set.
-- With 15 actives and 20 benefits, a complete matrix is expected to contain
-- 300 current active-benefit combinations.
CREATE OR REPLACE VIEW vw_missing_active_benefit_score AS
SELECT
    a.active_id,
    a.active_name,
    b.benefit_id,
    b.benefit_name
FROM active a
CROSS JOIN benefit b
LEFT JOIN vw_current_active_benefit_score abs
  ON abs.active_id = a.active_id
 AND abs.benefit_id = b.benefit_id
WHERE abs.active_id IS NULL;

COMMIT;

-- ============================================================================
-- IMPLEMENTATION / GOVERNANCE RULES (DOCUMENTATION)
-- ============================================================================
-- 1. concern_benefit is the ONLY manually curated bridge between skin concerns
--    and benefits for the recommendation model.
-- 2. Do not insert a permanent active<->skin_concern master mapping.
-- 3. Initial inferred mappings should use evidence_level='HYPOTHESIS'.
-- 4. CelRevive/domain-approved mappings should be introduced as a NEW
--    mapping_version; do not overwrite previous approved versions.
-- 5. Active-benefit score changes should similarly use a new score_version.
-- 6. Every concern/version must sum to exactly 1.00000 across its benefit weights.
-- 7. Recommendation APIs should normally query vw_ranked_active_concern_score.
-- 8. Suitability/safety/compatibility filtering is a separate stage from
--    relevance scoring and should be applied after concern relevance is derived.
-- ============================================================================
