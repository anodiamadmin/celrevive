-- ============================================================================
-- CelRevive PostgreSQL DDL - Updated Recommendation Architecture
-- Version: 2.0
-- Date: 2026-08-13
--
-- Purpose
--   Consolidated schema for CelRevive master/reference data, compatibility data,
--   operational formulation data, and the explainable recommendation model:
--
--     skin_concern
--         -> concern_benefit (weighted mapping)
--         -> benefit
--         -> active_benefit_score
--         -> active
--
--   IMPORTANT: Active-to-skin-concern relevance is DERIVED. It is intentionally
--   not maintained as a hard-coded master mapping table.
--
-- Notes
--   1. Existing business IDs are preserved as supplied by CelRevive:
--        active.active_id       = INTEGER (e.g. 1..15)
--        benefit.benefit_id     = INTEGER (e.g. 1..20)
--        skin_concern.concern_id = VARCHAR(10) (e.g. SC0001)
--   2. concern_benefit and active_benefit_score are versioned.
--   3. Weight-sum validation for concern_benefit is enforced by a deferred
--      constraint trigger so each concern/version must total 1.00000.
--   4. The ranking views use the latest available mapping version per concern
--      and the latest active/benefit score version per active-benefit pair.
-- ============================================================================

