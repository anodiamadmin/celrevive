'All weights for one concern/version must sum to 1.00000.';

-- Aggregate weight validation cannot be expressed with a row-level CHECK.
-- Use a deferred constraint trigger so multi-row inserts/updates can be made
-- within one transaction and are validated at transaction completion.
CREATE OR REPLACE FUNCTION validate_concern_benefit_weight_sum()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_weight_sum NUMERIC(12,8);
    v_row_count  INTEGER;
BEGIN
    -- Validate the OLD concern/version group for DELETE and for UPDATEs that
    -- move a row between concern/version groups.
    IF TG_OP IN ('DELETE', 'UPDATE') THEN
        SELECT COUNT(*), COALESCE(SUM(weight), 0)
          INTO v_row_count, v_weight_sum
          FROM concern_benefit
         WHERE concern_id = OLD.concern_id
           AND mapping_version = OLD.mapping_version;

        IF v_row_count > 0
           AND ABS(v_weight_sum - 1.00000) > 0.00001 THEN
            RAISE EXCEPTION
                'concern_benefit weights must sum to 1.00000. concern_id=%, mapping_version=%, current_sum=%',
                OLD.concern_id, OLD.mapping_version, v_weight_sum;
        END IF;
    END IF;

    -- Validate the NEW concern/version group for INSERT and UPDATE.
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        SELECT COUNT(*), COALESCE(SUM(weight), 0)
          INTO v_row_count, v_weight_sum
          FROM concern_benefit
         WHERE concern_id = NEW.concern_id
           AND mapping_version = NEW.mapping_version;

        IF v_row_count > 0
           AND ABS(v_weight_sum - 1.00000) > 0.00001 THEN
            RAISE EXCEPTION
                'concern_benefit weights must sum to 1.00000. concern_id=%, mapping_version=%, current_sum=%',
                NEW.concern_id, NEW.mapping_version, v_weight_sum;
        END IF;
    END IF;

    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_concern_benefit_weight_sum ON concern_benefit;

CREATE CONSTRAINT TRIGGER trg_validate_concern_benefit_weight_sum
AFTER INSERT OR UPDATE OR DELETE ON concern_benefit
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_concern_benefit_weight_sum();

