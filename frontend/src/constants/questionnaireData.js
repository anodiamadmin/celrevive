/**
 * Builds the exact canonical JSON structure required by FastAPI's validate_questionnaire_payload()
 */
export function buildCanonicalQuestionnairePayload(answers, allergyDetails = '') {
  const sections = SECTION_ORDER.map((sec) => {
    const secQuestions = QUESTIONS.filter((q) => q.section_id === sec.section_id).map((q) => {
      const baseQuestion = {
        question_id: q.id,
        question_number: q.question_number,
        question_text: q.question,
        question_type: q.question_type,
      };

      if (q.id === 'q2' || q.id === 'q19') {
        baseQuestion.max_selections = 3;
      }

      baseQuestion.options = q.options;

      if (q.question_type === 'single_select_with_conditional_text') {
        const selected = answers[q.id] || 'No';
        baseQuestion.conditional_field = {
          trigger_value: 'Yes',
          field_label: 'Please provide details',
          user_text_response: selected === 'Yes' ? allergyDetails.trim() : null,
        };
        baseQuestion.user_response = selected;
      } else if (q.question_type === 'multi_select') {
        baseQuestion.user_response = Array.isArray(answers[q.id]) ? answers[q.id] : [];
      } else {
        baseQuestion.user_response = answers[q.id] || null;
      }

      return baseQuestion;
    });

    return {
      section_id: sec.section_id,
      section_title: sec.section_title,
      questions: secQuestions,
    };
  });

  return {
    questionnaire: {
      title: 'AI Questionnaire',
      sections,
    },
  };
}